export function usStateCode(value: string): string {
  const normalized = value.trim().toLowerCase()
  return (
    usStates.find(
      ([code, name]) =>
        code.toLowerCase() === normalized || name.toLowerCase() === normalized
    )?.[0] ?? ""
  )
}
